/**
 * Localized weekday labels, Monday-first (index 0 = Monday), derived from the
 * locale-aware formatDate provided by useI18n(). 2024-01-01 is a Monday.
 */
export function buildWeekdayLabels(
  formatDate: (value: Date | number | string, options?: Intl.DateTimeFormatOptions) => string,
  weekday: "long" | "short" | "narrow" = "long"
): string[] {
  return Array.from({ length: 7 }, (_, index) =>
    formatDate(Date.UTC(2024, 0, 1 + index), { weekday, timeZone: "UTC" })
  )
}
